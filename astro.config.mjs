import { defineConfig } from 'astro/config';
import vue from '@astrojs/vue';
import tailwindcss from '@tailwindcss/vite';
import { templateCompilerOptions } from '@tresjs/core';
export default defineConfig({
  site: 'https://annakotl.github.io',
  base: '/upTilt',
  trailingSlash: 'always',
  output: 'static',
  integrations: [vue(templateCompilerOptions)],
  vite: {
    plugins: [
      tailwindcss(),
      {
        name: 'knowledge-index-dev-paths',
        apply: 'serve',
        configureServer(server) {
          // Astro's trailing-slash policy also applies to catch-all endpoints in dev.
          // Use their file URLs in the browser, as generated by the static build.
          const prefix = server.config.base + 'search-index/';
          server.middlewares.use((request, _response, next) => {
            const url = new URL(request.url ?? '/', 'http://localhost');
            if (
              url.pathname.startsWith(prefix) &&
              !url.pathname.endsWith('/')
            ) {
              request.url = url.pathname + '/' + url.search;
            }
            next();
          });
        },
      },
    ],
  },
});
